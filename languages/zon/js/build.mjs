// Wrap the WebAssembly module `zig build wasm` makes (zig-out/bin/fig-zon.wasm)
// as js/zon.js: the module, base64, under the language's name — the
// `NativeLanguage` `registerLanguage` takes. Inlined rather than shipped as
// a .wasm, so it loads the same under Node and every bundler.
import { readFileSync, writeFileSync } from "node:fs";

const wasm = readFileSync(new URL("../zig-out/bin/fig-zon.wasm", import.meta.url));
writeFileSync(
  new URL("./zon.js", import.meta.url),
  `// Generated by js/build.mjs from zig-out/bin/fig-zon.wasm.
/** @type {import("@diaryx/fig").NativeLanguage} */
export default { name: "zon", wasm: "${wasm.toString("base64")}" };
`,
);
