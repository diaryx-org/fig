// Build the fig WebAssembly module and inline it into the TypeScript source,
// then the kit's (`kit/rules-bytes.js`), and then each language's own
// package's module (`languages/<name>/` at the repository root).
//
// Builds `fig-capi` (fig's C ABI, in the Rust workspace at bindings/rust) for
// wasm32, then base64-encodes the resulting reactor module into
// `src/wasm-bytes.ts`. Inlining (rather than shipping a separate `.wasm`)
// keeps the published package a single JS payload that loads identically
// under Node and every bundler, with no `fetch`/`fs` path to special-case.
// The module imports nothing but the `fig_host` calls the binding supplies,
// so it instantiates synchronously.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..", "..");
const srcDir = resolve(here, "..", "src");
const workspace = repoRoot;
const out = join(workspace, "target", "wasm32-unknown-unknown", "wasm");

/** `cargo rustc` one crate of the workspace into a wasm32 module, with the
 *  size-first `wasm` profile; the module's bytes. */
function cargoWasm(crate, features = [], artifact = crate.replaceAll("-", "_")) {
  const args = ["rustc", "-p", crate, "--profile", "wasm", "--crate-type", "cdylib", "--target", "wasm32-unknown-unknown"];
  if (features.length) args.push("--features", features.join(","));
  console.error(`· cargo ${args.join(" ")}`);
  execFileSync("cargo", args, { cwd: workspace, stdio: "inherit" });
  return readFileSync(join(out, `${artifact}.wasm`));
}

// No format is compiled into the published module. Each is a module of its
// own the caller imports and registers (`@diaryx/fig-<name>`),
// which hands back its `Format` — so a page pays for the formats it uses and
// no others, and the module itself is the core alone: the tree, the editor's
// splice engine, serialization.
//
// FIG_WASM_LANGUAGES=all compiles every format in anyway (fig-capi's `bundle`
// feature): a reference module whose compiled formats the languages are held
// to (`scripts/record-compiled.mjs`). A language registered into such a
// module under a compiled format's name is refused as taken.
const LANGUAGES = ["json", "yaml", "toml", "zon", "figl", "ini", "dotenv", "properties", "plist", "nestedtext"];
const wanted = (process.env.FIG_WASM_LANGUAGES ?? "").trim();
if (wanted !== "" && wanted !== "all") throw new Error(`FIG_WASM_LANGUAGES: \`all\` or nothing, not \`${wanted}\``);

const wasm = cargoWasm("fig-capi", wanted === "all" ? ["bundle"] : []);
const base64 = wasm.toString("base64");
console.error(`· fig.wasm ${(wasm.length / 1024).toFixed(1)} KiB → ${(base64.length / 1024).toFixed(1)} KiB base64`);

const banner = `// @generated by scripts/build-wasm.mjs — do not edit by hand.
// The fig core (rust/fig-capi) compiled to a wasm32 reactor
// module, base64-encoded. Regenerate with \`npm run build:wasm\`.
`;

// Chunk the literal so editors/diff tools don't choke on one multi-hundred-KiB
// line, and emit it as an ARRAY joined at runtime rather than a `"a" + "b" + …`
// expression: a deep `+`-chain is parsed by recursive descent, so a large module
// overflows the stack of Node's lightweight TS type-stripper (and some bundlers).
// An array literal parses flat.
const chunks = [];
for (let i = 0; i < base64.length; i += 120) chunks.push(base64.slice(i, i + 120));
const literal = chunks.map((c) => `  "${c}",`).join("\n");

mkdirSync(srcDir, { recursive: true });
writeFileSync(
  join(srcDir, "wasm-bytes.ts"),
  `${banner}export const WASM_BASE64: string = [\n${literal}\n].join("");\n`,
);
console.error("· wrote src/wasm-bytes.ts");

// The kit's rules (`rust/fig-kit-capi`, `fig-kit.wasm`), which the
// JavaScript kit answers through (`kit/rules.js`): one line, as it is small.
const kitWasm = cargoWasm("fig-kit-capi");
writeFileSync(
  resolve(here, "..", "kit", "rules-bytes.js"),
  `// @generated by scripts/build-wasm.mjs — do not edit by hand.
// The kit's rules (rust/fig-kit-capi) compiled to WebAssembly, base64.
/** @type {string} */
export const BYTES = "${kitWasm.toString("base64")}";
`,
);
console.error(`· wrote kit/rules-bytes.js (fig-kit.wasm ${(kitWasm.length / 1024).toFixed(1)} KiB)`);

// Each language's own package (languages/<name>/, `@diaryx/fig-<name>`)
// builds its module and wraps it as `js/<name>.js`, as its `npm run build`
// does: the tests import them as the packages a caller installs.
for (const name of LANGUAGES) {
  const dir = join(repoRoot, "languages", name);
  execFileSync(process.execPath, ["js/build.mjs"], { cwd: dir, stdio: "inherit" });
  console.error(`· languages/${name}/js/${name}.js`);
}
