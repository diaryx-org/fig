// Build the fig WebAssembly module and inline it into the TypeScript source,
// and each language's own module into `languages/<name>.js`.
//
// Runs `zig build wasm` at the repository root, then base64-encodes the
// resulting freestanding reactor module into `src/wasm-bytes.ts`. Inlining
// (rather than shipping a separate `.wasm`) keeps the published package a single
// JS payload that loads identically under Node and every bundler, with no
// `fetch`/`fs` path to special-case. The module imports nothing, so it
// instantiates synchronously.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..", "..");
const srcDir = resolve(here, "..", "src");

// No format is compiled into the published module. Each is a module of its
// own the caller imports and registers (`@diaryx/fig/languages/<name>`),
// which hands back its `Format` — so a page pays for the formats it uses and
// no others, and the module itself is the core alone: the tree, the editor's
// splice engine, serialization.
//
// FIG_WASM_LANGUAGES names formats to compile in anyway, comma-separated, or
// `all` for every one: a reference module whose compiled formats the
// languages are held to (`scripts/record-printed.mjs`). A language registered
// into such a module under a compiled format's name is refused as taken.
const LANGUAGES = ["json", "yaml", "toml", "zon", "figl", "ini", "dotenv", "properties", "plist", "nestedtext"];
const wanted = (process.env.FIG_WASM_LANGUAGES ?? "").split(",").map((s) => s.trim()).filter(Boolean);
for (const w of wanted) {
  if (w !== "all" && !LANGUAGES.includes(w)) throw new Error(`FIG_WASM_LANGUAGES: no format named \`${w}\` (one of ${LANGUAGES.join(", ")}, or all)`);
}
const on = (name) => wanted.includes("all") || wanted.includes(name);
const zigArgs = ["build", "wasm", ...LANGUAGES.map((name) => `-D${name}=${on(name)}`)];

console.error(`· zig ${zigArgs.join(" ")}`);
execFileSync("zig", zigArgs, { cwd: repoRoot, stdio: "inherit" });

const wasmPath = join(repoRoot, "zig-out", "bin", "fig.wasm");
const wasm = readFileSync(wasmPath);
const base64 = wasm.toString("base64");
console.error(`· fig.wasm ${(wasm.length / 1024).toFixed(1)} KiB → ${(base64.length / 1024).toFixed(1)} KiB base64`);

const banner = `// @generated by scripts/build-wasm.mjs — do not edit by hand.
// The fig core (src/c_api.zig) compiled to a freestanding wasm32 reactor
// module, base64-encoded. Regenerate with \`npm run build:wasm\`.
`;

// Chunk the literal so editors/diff tools don't choke on one multi-hundred-KiB
// line, and emit it as an ARRAY joined at runtime rather than a `"a" + "b" + …`
// expression: a deep `+`-chain is parsed by recursive descent, so a large module
// overflows the stack of Node's lightweight TS type-stripper (and some bundlers).
// An array literal parses flat.
const chunks = [];
for (let i = 0; i < base64.length; i += 120) chunks.push(base64.slice(i, i + 120));
const literal = chunks.map((c) => `  "${c}",`).join("\n");

mkdirSync(srcDir, { recursive: true });
writeFileSync(
  join(srcDir, "wasm-bytes.ts"),
  `${banner}export const WASM_BASE64: string = [\n${literal}\n].join("");\n`,
);
console.error("· wrote src/wasm-bytes.ts");

// Each language's own module (`zig build wasm-languages`), inlined into
// `languages/<name>.js` beside a declaration of its type. JSON's module
// serves JSONC and JSON5 too; `languages/json5.js` is it under the name the
// JavaScript languages give that pair.
const langArgs = ["build", "wasm-languages"];
console.error(`· zig ${langArgs.join(" ")}`);
execFileSync("zig", langArgs, { cwd: repoRoot, stdio: "inherit" });
const langDir = resolve(here, "..", "languages");
mkdirSync(langDir, { recursive: true });
const declaration = `import type { NativeLanguage } from "@diaryx/fig";
declare const language: NativeLanguage;
export default language;
`;
for (const name of LANGUAGES) {
  const module = readFileSync(join(repoRoot, "zig-out", "bin", `fig-${name}.wasm`));
  const b64 = module.toString("base64");
  const parts = [];
  for (let i = 0; i < b64.length; i += 120) parts.push(`  "${b64.slice(i, i + 120)}",`);
  writeFileSync(
    join(langDir, `${name}.js`),
    `// @generated by scripts/build-wasm.mjs — do not edit by hand.
// fig's ${name} language (src/languages/${name}/ in the core), compiled to a
// WebAssembly module of its own and base64-encoded. Register it with
// \`registerLanguage\`. Regenerate with \`npm run build:wasm\`.
/** @type {import("@diaryx/fig").NativeLanguage} */
const language = {
  name: "${name}",
  wasm: [
${parts.join("\n")}
  ].join(""),
};
export default language;
`,
  );
  writeFileSync(join(langDir, `${name}.d.ts`), declaration);
  console.error(`· languages/${name}.js ${(module.length / 1024).toFixed(1)} KiB`);
}
writeFileSync(join(langDir, "json5.js"), `// @generated by scripts/build-wasm.mjs: JSON's module, which serves JSONC and JSON5.\nexport { default } from "./json.js";\n`);
writeFileSync(join(langDir, "json5.d.ts"), declaration);
