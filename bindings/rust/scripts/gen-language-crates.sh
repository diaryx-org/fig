#!/usr/bin/env bash
# Write the crate of each language fig ships, `fig-<name>`: a Cargo.toml,
# the shared build script (`language-crate/build.rs`, which compiles
# `libfig_<name>.a`), and a lib.rs whose `register()` registers the language
# through `fig_<name>_register`. Rerun after editing the template or adding
# a language; the crates are generated, so edit them here.
#
# usage: scripts/gen-language-crates.sh
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(dirname "$here")"

# name|title|dialects
languages=(
  "json|JSON, JSONC and JSON5|\`json\`, \`jsonc\` and \`json5\`"
  "yaml|YAML|\`yaml\`, and each version as \`yaml-<version>\` (\`yaml-1.1\`)"
  "toml|TOML|\`toml\`, and each version as \`toml-<version>\` (\`toml-1.0\`)"
  "zon|ZON, Zig Object Notation|\`zon\`"
  "figl|figl, fig's authoring dialect|\`figl\`"
  "ini|INI|\`ini\`"
  "dotenv|dotenv|\`dotenv\`"
  "properties|Java \`.properties\`|\`properties\`"
  "plist|the Apple XML property list|\`plist\`"
  "nestedtext|NestedText|\`nestedtext\`"
)

for row in "${languages[@]}"; do
  IFS='|' read -r name title dialects <<<"$row"
  dir="$root/fig-$name"
  mkdir -p "$dir/src"
  cp "$here/language-crate/build.rs" "$dir/build.rs"
  serde_feature=""
  serde_dep=""
  if [ "$name" = yaml ]; then
    serde_feature=$'\n[features]\n# `from_str` and `to_string`: typed values to and from YAML text.\nserde = ["fig/serde", "dep:serde"]\n'
    serde_dep=$'serde = { version = "1", optional = true }\n'
  fi
  cat >"$dir/Cargo.toml" <<EOF
# @generated by scripts/gen-language-crates.sh — edit the script, not this file.
[package]
name = "fig-$name"
version.workspace = true
edition.workspace = true
rust-version.workspace = true
license.workspace = true
description = "$title for fig: fig's own parser, printer and editing rules for the language, as a library linked beside fig's."
repository = "https://github.com/diaryx-org/fig"
homepage = "https://github.com/diaryx-org/fig"
documentation = "https://docs.rs/fig-$name"
keywords = ["config", "fig", "$name", "parser"]
categories = ["config", "parser-implementations"]
# The language's own library, \`libfig_$name.a\`.
links = "fig_$name"

[dependencies]
fig = { workspace = true }
fig-sys = { workspace = true }
${serde_dep}${serde_feature}
EOF
  cat >"$dir/src/lib.rs" <<EOF
// @generated by scripts/gen-language-crates.sh — edit the script, not this file.
//! $title for [fig](https://docs.rs/fig): fig's own parser, printer and
//! editing rules for the language, compiled into a library of its own that
//! links beside fig's, which carries no language. Register it once, before
//! reaching for a format of it:
//!
//! \`\`\`ignore
//! let format = fig_$name::register()?;
//! let doc = fig::Document::parse(input, format)?;
//! \`\`\`
//!
//! It registers $dialects, each found by name with
//! [\`fig::Format::by_name\`].

use std::os::raw::c_int;

unsafe extern "C" {
    fn fig_${name}_register(out_format: *mut c_int, out_err: *mut fig_sys::FigError) -> fig_sys::FigStatus;
}

/// Register $title, and return the format of its first dialect.
/// Registering it again returns the format it already has.
pub fn register() -> Result<fig::Format, fig::Error> {
    // SAFETY: \`fig_${name}_register\` is this crate's library's, which its
    // build script links.
    unsafe { fig::language::register_library(fig_${name}_register) }
}
EOF
  if [ "$name" = yaml ]; then
    cat >>"$dir/src/lib.rs" <<'EOF'

/// Deserialize YAML text into a typed value: [`fig::from_slice`] with YAML
/// registered.
#[cfg(feature = "serde")]
pub fn from_str<T: serde::de::DeserializeOwned>(s: &str) -> Result<T, fig::Error> {
    fig::from_slice(s.as_bytes(), register()?)
}

/// Serialize a value to YAML text: [`fig::to_value`], then
/// [`fig::Value::serialize`] as YAML.
#[cfg(feature = "serde")]
pub fn to_string<T: serde::Serialize + ?Sized>(value: &T) -> Result<String, fig::Error> {
    fig::to_value(value)?.serialize(register()?)
}
EOF
  fi
done
# Formatted as `cargo fmt` would, so a regeneration is fmt-clean.
for row in "${languages[@]}"; do
  IFS='|' read -r name _ <<<"$row"
  rustfmt --edition 2024 "$root/fig-$name/build.rs" "$root/fig-$name/src/lib.rs"
done
echo "gen-language-crates: wrote ${#languages[@]} crates"
