// Build the language's WebAssembly module from its Rust (`fig-lang-export`
// with its `figl` feature, in fig's Rust workspace) and wrap it
// as js/figl.js: the module, base64, under the language's name — the
// `NativeLanguage` `registerLanguage` takes. Inlined rather than shipped as
// a .wasm, so it loads the same under Node and every bundler.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const workspace = new URL("../../../", import.meta.url);
execFileSync(
  "cargo",
  ["rustc", "-p", "fig-lang-export", "--features", "figl", "--profile", "wasm", "--crate-type", "cdylib", "--target", "wasm32-unknown-unknown"],
  { cwd: workspace, stdio: "inherit" },
);
const wasm = readFileSync(new URL("target/wasm32-unknown-unknown/wasm/fig_lang_export.wasm", workspace));
writeFileSync(
  new URL("./figl.js", import.meta.url),
  `// Generated by js/build.mjs from fig-lang-export's wasm build.
/** @type {import("@diaryx/fig").NativeLanguage} */
export default { name: "figl", wasm: "${wasm.toString("base64")}" };
`,
);
