// Wrap the WebAssembly module `zig build wasm` makes (zig-out/bin/fig-yaml.wasm)
// as js/yaml.js: the module, base64, under the language's name — the
// `NativeLanguage` `registerLanguage` takes. Inlined rather than shipped as
// a .wasm, so it loads the same under Node and every bundler.
import { readFileSync, writeFileSync } from "node:fs";

const wasm = readFileSync(new URL("../zig-out/bin/fig-yaml.wasm", import.meta.url));
writeFileSync(
  new URL("./yaml.js", import.meta.url),
  `// Generated by js/build.mjs from zig-out/bin/fig-yaml.wasm.
/** @type {import("@diaryx/fig").NativeLanguage} */
export default { name: "yaml", wasm: "${wasm.toString("base64")}" };
`,
);
